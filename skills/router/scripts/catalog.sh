#!/usr/bin/env bash
# Router catalog generator — scans every installed skill (personal + plugins) and
# writes a compact routing index to references/skill-catalog.md.
# Run on demand or from the SessionStart hook so the catalog never goes stale as
# skills are added/removed. This is the "self-improving" substrate: the router
# always routes against the CURRENT set of skills, not a hand-maintained list.
set -euo pipefail

ROUTER_DIR="$HOME/.claude/skills/router"
OUT="$ROUTER_DIR/references/skill-catalog.md"
mkdir -p "$ROUTER_DIR/references"

extract_desc() {
  # First `description:` line from a SKILL.md frontmatter; strip quotes; trim to 240 chars.
  awk '/^description:/{sub(/^description:[[:space:]]*/,"");gsub(/^"|"$/,"");print;exit}' "$1" 2>/dev/null \
    | tr '\n' ' ' | sed 's/  */ /g' | cut -c1-240
}

tmp="$(mktemp)"
count=0

# Personal skills
for d in "$HOME"/.claude/skills/*/; do
  name="$(basename "$d")"
  [ "$name" = "router" ] && continue          # don't route to self
  [ "$name" = "_shared-references" ] && continue
  sk="$d/SKILL.md"
  [ -f "$sk" ] || continue
  desc="$(extract_desc "$sk")"
  [ -z "$desc" ] && desc="(no description)"
  printf -- "- **%s** — %s\n" "$name" "$desc" >> "$tmp"
  count=$((count+1))
done

# Plugin skills (namespaced plugin:skill when invoked)
if compgen -G "$HOME/.claude/plugins/*/skills/*/SKILL.md" > /dev/null 2>&1; then
  for sk in "$HOME"/.claude/plugins/*/skills/*/SKILL.md; do
    skill="$(basename "$(dirname "$sk")")"
    plugin="$(basename "$(dirname "$(dirname "$(dirname "$sk")")")")"
    desc="$(extract_desc "$sk")"
    [ -z "$desc" ] && desc="(no description)"
    printf -- "- **%s:%s** — %s\n" "$plugin" "$skill" "$desc" >> "$tmp"
    count=$((count+1))
  done
fi

{
  echo "# Skill Catalog (auto-generated)"
  echo ""
  echo "> Regenerated by \`scripts/catalog.sh\`. **$count skills** as of $(date '+%Y-%m-%d %H:%M %Z')."
  echo "> The router reads this to pick the best skill(s) for a task. Do not hand-edit — edit skills, then rerun."
  echo ""
  sort -f "$tmp"
} > "$OUT"

rm -f "$tmp"
echo "router: wrote $count skills to $OUT"
